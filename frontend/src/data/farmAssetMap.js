const PRODUCE = {
  kf_tomato_plant: 'kf_tomato',
  kf_carrot_plant: 'kf_carrot',
  kf_turnip_plant: 'kf_turnip',
  kf_corn_plant: 'kf_corn',
  kf_cabbage_plant: 'kf_cabbage',
  kf_wheat_plant: 'kf_wheat',
};

export function realFarmSprite(key, action = '') {
  if (!key) return key;
  let mapped = key.startsWith('kf_') ? key : FARM_SPRITE_REAL[key] || key;
  if (
    (action === 'collect' || action === 'arrange') &&
    PRODUCE[mapped]
  ) {
    return PRODUCE[mapped];
  }
  return mapped;
}
